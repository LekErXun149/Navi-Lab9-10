function phaseD_report(rows, SC, OPT, cfg, outdir)
%PHASED_REPORT  Turn Phase D results into DTEST_RESULTS.md, phaseD_metrics.csv and figures.
%   phaseD_report(rows, SC, OPT, cfg, outdir)    (called by phaseD_run)
%   or reload:  load results/phaseD_results.mat; phaseD_report(rows, phaseD_scenarios(cfg0), OPT, cfg0, 'results')

ids = {rows.id}; ver = {rows.version}; prof = {rows.profile};
M = [rows.m];
val = @(f, mask) [M(mask).(f)];
has = @(v) any(strcmp(OPT.versions, v));
simIds = cellfun(@(s) s.id, SC(cellfun(@(s) strcmp(s.type, 'sim'), SC)), 'UniformOutput', false);
isSim = ismember(ids, simIds);

%% ---- CSV with every run -------------------------------------------------
f = fieldnames(M);
fid = fopen(fullfile(outdir, 'phaseD_metrics.csv'), 'w');
fprintf(fid, 'scenario,profile,run,version'); fprintf(fid, ',%s', f{:}); fprintf(fid, '\n');
for i = 1:numel(rows)
    fprintf(fid, '%s,%s,%d,%s', rows(i).id, rows(i).profile, rows(i).run, rows(i).version);
    for k = 1:numel(f), fprintf(fid, ',%s', num(double(rows(i).m.(f{k})))); end
    fprintf(fid, '\n');
end
fclose(fid);

%% ---- markdown -------------------------------------------------------------
fid = fopen(fullfile(outdir, 'DTEST_RESULTS.md'), 'w');
fprintf(fid, '# Phase D - scenario test results\n\n');
if isempty(OPT.clearance), cl = 'the fence in uwb_config.m'; else, cl = sprintf('a fence %.1f m from the lanes (phaseD_site)', OPT.clearance); end
fprintf(fid, 'Generated by `phaseD_run.m` on %s. %d runs per scenario and noise profile (%s); versions: %s; site: %s.\n\n', ...
    datestr(now, 'yyyy-mm-dd HH:MM'), OPT.runs, strjoin(OPT.profiles, ', '), strjoin(OPT.versions, ', '), cl);
fprintf(fid, 'True person positions are scripted; ranges are simulated with real errors from the 26-Oct recordings; ');
fprintf(fid, 'everything after that is the real pipeline (trilateration, Kalman filter, safety logic, AGV simulation). ');
fprintf(fid, 'Safety numbers use the TRUE position. Near miss = an AGV faster than CRAWL (0.2 m/s) within 0.5 m of the person; ');
fprintf(fid, 'contact = an AGV still moving touches the person.\n\n');

% headline: full vs basic
if has('full') && has('basic')
    fprintf(fid, '## 1. This system vs "stop every AGV whenever anyone is inside the fence"\n\n');
    mF = isSim & strcmp(ver, 'full'); mB = isSim & strcmp(ver, 'basic');
    [d, lo, hi, nP] = pairdiff(rows, mF, mB, 'prod');
    fprintf(fid, '| | This system | Basic |\n|---|---|---|\n');
    fprintf(fid, '| Near misses (all scenarios, all runs) | %d | %d |\n', sum(val('nearMiss', mF)), sum(val('nearMiss', mB)));
    fprintf(fid, '| Contacts | %d | %d |\n', sum(val('contact', mF)), sum(val('contact', mB)));
    fprintf(fid, '| Closest AGV faster than CRAWL, worst run (m) | %s | %s |\n', num(min(val('minClear', mF))), num(min(val('minClear', mB))));
    fprintf(fid, '| AGV productivity, mean over all scenarios (%%) | %s | %s |\n', num(mean(val('prod', mF))), num(mean(val('prod', mB))));
    for p = 1:numel(OPT.profiles)
        a = val('prod', strcmp(ids, 'S18') & strcmp(ver, 'full') & strcmp(prof, OPT.profiles{p}));
        b = val('prod', strcmp(ids, 'S18') & strcmp(ver, 'basic') & strcmp(prof, OPT.profiles{p}));
        if ~isempty(a)
            fprintf(fid, '| **Work shift S18** productivity, %s noise (%%) | **%s +- %s** | %s +- %s |\n', ...
                OPT.profiles{p}, num(mean(a)), num(sd(a)), num(mean(b)), num(sd(b)));
        end
    end
    fprintf(fid, '\n**Safety by noise profile** (near misses / contacts / closest AGV faster than CRAWL):\n\n');
    fprintf(fid, '| Noise profile | This system | Basic |\n|---|---|---|\n');
    for p = 1:numel(OPT.profiles)
        a = mF & strcmp(prof, OPT.profiles{p}); b = mB & strcmp(prof, OPT.profiles{p});
        fprintf(fid, '| %s | %d / %d / %s m | %d / %d / %s m |\n', OPT.profiles{p}, ...
            sum(val('nearMiss', a)), sum(val('contact', a)), num(min(val('minClear', a))), ...
            sum(val('nearMiss', b)), sum(val('contact', b)), num(min(val('minClear', b))));
        for s = 1:numel(SC)                               % where they happened
            k = a & strcmp(ids, SC{s}.id);
            if any(val('nearMiss', k) > 0 | val('contact', k)), fprintf(fid, '|  - in %s (%s) | %d / %d | |\n', SC{s}.id, SC{s}.name, sum(val('nearMiss', k)), sum(val('contact', k))); end
        end
    end
    fprintf(fid, '\n`typical` = errors of the 15:33 recording; `worst` = tag-under-A3 recording (tag 0.74 m below the anchors, NLOS): position errors up to ~1 m.\n');
    fprintf(fid, '\nPaired difference in productivity (same scenario, noise and run): **%+.1f percentage points** ', d);
    fprintf(fid, '(95%% confidence interval %+.1f to %+.1f, %d pairs).\n\n', lo, hi, nP);
end

% pass table for the full system
fprintf(fid, '## 2. Pass / fail of this system per scenario\n\n');
fprintf(fid, '| ID | Scenario | Pass if | Passed | Closest moving AGV (m, worst) | Productivity (%%) |\n|---|---|---|---|---|---|\n');
for s = 1:numel(SC)
    k = strcmp(ids, SC{s}.id) & strcmp(ver, 'full');
    if ~any(k), continue; end
    fprintf(fid, '| %s | %s | %s | %d / %d | %s | %s |\n', SC{s}.id, SC{s}.name, SC{s}.passText, ...
        sum(val('pass', k)), nnz(k), num(min(val('minClear', k))), num(mean(val('prod', k))));
end

% full vs basic per scenario
if has('full') && has('basic')
    fprintf(fid, '\n## 3. Per scenario: this system vs basic (mean over runs and noise profiles)\n\n');
    fprintf(fid, '| ID | Productivity this / basic (%%) | STOP commands this / basic | Near misses this / basic | Warning before lane this / basic (s) |\n|---|---|---|---|---|\n');
    for s = 1:numel(SC)
        kF = strcmp(ids, SC{s}.id) & strcmp(ver, 'full'); kB = strcmp(ids, SC{s}.id) & strcmp(ver, 'basic');
        if ~any(kF), continue; end
        fprintf(fid, '| %s | %s / %s | %s / %s | %d / %d | %s / %s |\n', SC{s}.id, ...
            num(mean(val('prod', kF))), num(mean(val('prod', kB))), ...
            num(mean(val('stopCmds', kF))), num(mean(val('stopCmds', kB))), ...
            sum(val('nearMiss', kF)), sum(val('nearMiss', kB)), ...
            num(nmean(val('warn', kF))), num(nmean(val('warn', kB))));
    end
end

% ablation
abl = OPT.versions;
if numel(abl) > 2
    fprintf(fid, '\n## 4. What each enhancement adds (one switched off at a time)\n\n');
    fprintf(fid, '| Version | Near misses | Closest moving AGV (m) | Productivity (%%) | Flicker S12 (/AGV/min) | Warning S5+S6 (s) | Passed AGV kept moving S9+S10 (%%) | STOP held under NLOS S16 (%%) |\n|---|---|---|---|---|---|---|---|\n');
    for v = 1:numel(abl)
        k = isSim & strcmp(ver, abl{v});
        fprintf(fid, '| %s | %d | %s | %s | %s | %s | %s | %s |\n', abl{v}, sum(val('nearMiss', k)), ...
            num(min(val('minClear', k))), num(mean(val('prod', k))), ...
            num(nmean(val('flicker', k & strcmp(ids, 'S12')))), ...
            num(nmean(val('warn', k & ismember(ids, {'S5', 'S6'})))), ...
            num(100 * nmean(val('kept', k & ismember(ids, {'S9', 'S10'})))), ...
            num(100 * nmean(val('held', k & strcmp(ids, 'S16')))));
    end
    fprintf(fid, '\nfull = all on; basic = stop all inside the fence; noE1 = no time-to-lane; noE2 = whole lane stops; ');
    fprintf(fid, 'noE3 = fixed %.2f m buffer; noE5 = no hysteresis/dwell.\n', cfg.policy.fixedBuf);
end
fprintf(fid, '\n## Notes\n\n- The AGVs are simulated (speed %.1f m/s, braking %.1f m/s^2, latency %.1f s - assumed values).\n', ...
    cfg.agv.vMax, cfg.agv.decel, cfg.agv.latency);
fprintf(fid, '- The site is `cfg.site` in `uwb_config.m`; re-run after changing it.\n');
fprintf(fid, '- S17 has no ground truth: its distances are to the estimated position.\n');
fclose(fid);

%% ---- figures ------------------------------------------------------------
if has('full') && has('basic')
    fig = figure('Name', 'Phase D', 'Color', 'w', 'Position', [60 60 1200 500], 'Visible', 'off');
    try theme(fig, 'light'); catch, end
    subplot(1, 2, 1);
    sid = unique(ids(isSim), 'stable'); pf = zeros(numel(sid), 2);
    for s = 1:numel(sid)
        pf(s, 1) = mean(val('prod', strcmp(ids, sid{s}) & strcmp(ver, 'full')));
        pf(s, 2) = mean(val('prod', strcmp(ids, sid{s}) & strcmp(ver, 'basic')));
    end
    bar(pf); set(gca, 'XTick', 1:numel(sid), 'XTickLabel', sid); grid on;
    legend('this system', 'basic: stop all inside fence', 'Location', 'southwest');
    ylabel('AGV productivity (%)'); title('Productivity per scenario'); ylim([0 105]);
    subplot(1, 2, 2); hold on; grid on; box on;
    for v = 1:numel(abl)
        k = isSim & strcmp(ver, abl{v});
        c = val('minClear', k); c = c(isfinite(c));
        x = mean(val('prod', k)); y = prctile5(c);
        plot(x, y, 'o', 'MarkerSize', 9, 'LineWidth', 1.5);
        text(x + 0.5, y, sprintf(' %s (%d near misses)', abl{v}, sum(val('nearMiss', k))));
    end
    plot(xlim, [0.5 0.5], 'r--');
    xlabel('AGV productivity, mean over scenarios (%)'); ylabel('closest moving AGV, 5th percentile (m)');
    title('Safety vs productivity per version (red: near-miss line)');
    print(fig, fullfile(outdir, 'phaseD_comparison.png'), '-dpng', '-r110');
    close(fig);
end

%% ---- console summary ------------------------------------------------------
fprintf('\nResults written to %s\n', outdir);
type(fullfile(outdir, 'DTEST_RESULTS.md'));
end

% -------------------------------------------------------------------------
function [d, lo, hi, n] = pairdiff(rows, mA, mB, field)
% paired difference A - B over identical scenario/profile/run
a = rows(mA); b = rows(mB); x = [];
for i = 1:numel(a)
    j = find(strcmp({b.id}, a(i).id) & strcmp({b.profile}, a(i).profile) & [b.run] == a(i).run, 1);
    if ~isempty(j), x(end+1) = a(i).m.(field) - b(j).m.(field); end %#ok<AGROW>
end
n = numel(x); d = mean(x); h = 1.96 * std(x) / sqrt(max(n, 1)); lo = d - h; hi = d + h;
end
function s = num(x)
if isempty(x) || ~isfinite(x), s = '-'; elseif abs(x - round(x)) < 1e-9 && abs(x) < 1e6, s = sprintf('%d', round(x));
else, s = sprintf('%.2f', x); end
end
function m = nmean(x), x = x(isfinite(x)); if isempty(x), m = NaN; else, m = mean(x); end, end
function s = sd(x), if numel(x) < 2, s = 0; else, s = std(x); end, end
function p = prctile5(x), x = sort(x); if isempty(x), p = NaN; else, p = x(max(1, round(0.05 * numel(x)))); end, end
